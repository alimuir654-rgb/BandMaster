#!/usr/bin/env python3
"""Authenticated encrypted backup of the existing Playtest JKS and passwords.

No APK access, network calls, signing-key generation/rotation or secret output. The only
new key generated by create_backup is a separate backup-encryption secret.
"""
import base64
from contextlib import contextmanager
import hashlib
import json
import os
from pathlib import Path
import stat
import subprocess
import tempfile
from cryptography.exceptions import InvalidTag
from cryptography.hazmat.primitives.ciphers.aead import AESGCM

CERT = '83c797fe8db043b49ebdc705a3ca7a0326db19d0b9bf613c8cb1db1ea0c3cbf2'
APP = 'com.bandmaster.ownerplaytest.s40'
ALIAS = 'androiddebugkey'
AAD = b'BandMaster original Playtest signing backup v1'
FORMAT = 'bandmaster-signing-backup-v1'
LIMIT = 65536


def require(ok, message):
    if not ok:
        raise ValueError(message)


def exclusive_private(path, data):
    with os.fdopen(os.open(path, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600), 'wb') as f:
        f.write(data)


def read_recovery_secret(path):
    info = path.lstat()
    require(stat.S_ISREG(info.st_mode) and not path.is_symlink(), 'Recovery secret must be a regular file')
    require(info.st_mode & 0o077 == 0 and info.st_uid == os.getuid(), 'Recovery secret must be owner-only')
    require(info.st_size == 32, 'Recovery secret must contain exactly 32 raw bytes')
    return path.read_bytes()


def original_certificate(keystore, alias, passwords):
    require(alias == ALIAS and keystore.is_file(), 'Existing original alias/keystore required')
    with tempfile.TemporaryDirectory(prefix='bm-public-cert-') as work:
        cert = Path(work) / 'cert.der'
        result = subprocess.run(['keytool', '-exportcert', '-alias', alias, '-keystore', str(keystore),
                                 '-storepass:env', 'BM_STORE_PASSWORD', '-file', str(cert)],
                                env=passwords, capture_output=True, timeout=30)
        require(result.returncode == 0, 'Original certificate check refused; details withheld')
        require(hashlib.sha256(cert.read_bytes()).hexdigest() == CERT, 'Original certificate pin mismatch')
    return CERT


def create_backup(keystore, alias, output, recovery_key_file, passwords):
    require(not output.exists() and not output.is_symlink(), 'Backup output already exists')
    require(all(passwords.get(k) for k in ['BM_STORE_PASSWORD', 'BM_KEY_PASSWORD']), 'Secure password bindings required')
    original_certificate(keystore, alias, passwords)
    raw = keystore.read_bytes()
    require(0 < len(raw) < LIMIT // 2, 'Unexpected original keystore size')
    if not recovery_key_file.exists():
        exclusive_private(recovery_key_file, AESGCM.generate_key(bit_length=256))
    key = read_recovery_secret(recovery_key_file)
    payload = dict(format=FORMAT, alias=alias, certificate_sha256=CERT, application_id=APP,
                   keystore_base64=base64.b64encode(raw).decode(),
                   store_password=passwords['BM_STORE_PASSWORD'], key_password=passwords['BM_KEY_PASSWORD'])
    nonce = os.urandom(12)
    ciphertext = AESGCM(key).encrypt(nonce, json.dumps(payload, separators=(',', ':')).encode(), AAD)
    blob = dict(format=FORMAT, nonce_base64=base64.b64encode(nonce).decode(),
                ciphertext_base64=base64.b64encode(ciphertext).decode())
    wire = (json.dumps(blob, indent=2) + '\n').encode()
    require(len(wire) <= LIMIT, 'Encrypted backup exceeds recovery size limit')
    exclusive_private(output, wire)
    return dict(certificate_sha256=CERT, alias=alias, backup_sha256=hashlib.sha256(output.read_bytes()).hexdigest(),
                keystore_sha256=hashlib.sha256(raw).hexdigest())


def decrypt_backup(backup, recovery_key_file):
    require(0 < backup.stat().st_size <= LIMIT, 'Unexpected encrypted backup size')
    outer = json.loads(backup.read_bytes())
    require(set(outer) == {'format', 'nonce_base64', 'ciphertext_base64'} and outer['format'] == FORMAT,
            'Unsupported encrypted backup envelope')
    nonce = base64.b64decode(outer['nonce_base64'], validate=True)
    encrypted = base64.b64decode(outer['ciphertext_base64'], validate=True)
    require(len(nonce) == 12 and len(encrypted) >= 16, 'Invalid encrypted backup envelope')
    try:
        raw = AESGCM(read_recovery_secret(recovery_key_file)).decrypt(nonce, encrypted, AAD)
    except InvalidTag:
        raise ValueError('Encrypted backup authentication failed') from None
    payload = json.loads(raw)
    require(set(payload) == {'format', 'alias', 'certificate_sha256', 'application_id', 'keystore_base64',
                             'store_password', 'key_password'}, 'Unsupported recovered fields')
    require(payload['format'] == FORMAT and payload['alias'] == ALIAS and payload['certificate_sha256'] == CERT
            and payload['application_id'] == APP, 'Recovered signing identity mismatch')
    require(all(isinstance(payload[k], str) and payload[k] for k in ['store_password', 'key_password']),
            'Recovered passwords absent')
    store = base64.b64decode(payload['keystore_base64'], validate=True)
    require(0 < len(store) < LIMIT // 2, 'Unexpected recovered keystore size')
    return payload, store


@contextmanager
def recovered_store(backup, recovery_key_file):
    # Authenticate and validate before writing any recovered private material.
    payload, raw = decrypt_backup(backup, recovery_key_file)
    with tempfile.TemporaryDirectory(prefix='bm-recovered-key-') as work:
        root = Path(work)
        root.chmod(0o700)
        store = root / 'original.jks'
        exclusive_private(store, raw)
        environment = os.environ.copy()
        environment['BM_STORE_PASSWORD'] = payload['store_password']
        environment['BM_KEY_PASSWORD'] = payload['key_password']
        original_certificate(store, payload['alias'], environment)
        try:
            yield store, payload['alias'], environment
        finally:
            environment.pop('BM_STORE_PASSWORD', None)
            environment.pop('BM_KEY_PASSWORD', None)
    # TemporaryDirectory removes only this new private recovery stage. Python
    # objects/process memory are not claimed to be cryptographically zeroised.
